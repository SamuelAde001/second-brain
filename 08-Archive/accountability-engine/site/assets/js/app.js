/* ============================================================================
   Samuelsignals OS — shared runtime

   Data comes from window.OS, injected by data/os.js, which is generated by
   tools/site/build.py from context/*.md. Nothing on this site is hand-written
   data — if a number is wrong, the fix is in context/, never here.
   ========================================================================= */

const OS = window.OS || null;

/* ------------------------------------------------------------- formatting */

const naira = (n, opts = {}) => {
  if (n === null || n === undefined || isNaN(n)) return '—';
  const abs = Math.abs(n);
  if (opts.short && abs >= 1_000_000) return `₦${(n / 1_000_000).toFixed(abs >= 10_000_000 ? 0 : 2)}M`;
  if (opts.short && abs >= 1_000) return `₦${(n / 1_000).toFixed(abs >= 100_000 ? 0 : 1)}k`;
  return '₦' + Math.round(n).toLocaleString('en-NG');
};

const num = (n, dp = 0) =>
  (n === null || n === undefined || isNaN(n)) ? '—' : Number(n).toFixed(dp);

const pct = n => (n === null || n === undefined || isNaN(n)) ? '—' : Math.round(n) + '%';

const hours = h => {
  if (h === null || h === undefined) return '—';
  if (h < 1) return `${Math.round(h * 60)}m`;
  const H = Math.floor(h), M = Math.round((h - H) * 60);
  return M ? `${H}h ${M}m` : `${H}h`;
};

const time12 = t => {
  if (!t) return '—';
  const [H, M] = t.split(':').map(Number);
  const ap = H < 12 ? 'am' : 'pm';
  const h = H % 12 === 0 ? 12 : H % 12;
  return `${h}:${String(M).padStart(2, '0')}${ap}`;
};

const dateLabel = iso => {
  if (!iso) return '—';
  return new Date(iso + 'T00:00:00').toLocaleDateString('en-GB',
    { weekday: 'short', day: 'numeric', month: 'short' });
};

const dayName = iso =>
  new Date(iso + 'T00:00:00').toLocaleDateString('en-GB', { weekday: 'long' });

/* --------------------------------------------------------------- the clock */

/* The record's "today" is the last ledger row, not the browser's clock. The
   site is a view of what was written down, and pretending otherwise would let a
   stale build silently claim to be current. */
const RECORD_TODAY = OS?.summary?.today || null;

function daysUntil(iso, from = RECORD_TODAY) {
  if (!iso || !from) return null;
  const a = new Date(from + 'T00:00:00'), b = new Date(iso + 'T00:00:00');
  return Math.round((b - a) / 86400000);
}

const daysLabel = d => {
  if (d === null) return '—';
  if (d === 0) return 'today';
  if (d === 1) return 'tomorrow';
  if (d < 0) return `${Math.abs(d)}d ago`;
  return `${d} days`;
};


/* ------------------------------------------------------------- markdown */

/* A small renderer for the domain files. Deliberately narrow: it handles the
   subset context/*.md actually uses — headings, bold, italic, code, links,
   lists, tables, blockquotes, rules — and nothing else. The point is that the
   prose on this site IS the file, so it can never drift from the record. */
function md(src) {
  const esc = t => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const inline = t => esc(t)
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/(^|[^*])\*([^*\n]+)\*/g, '$1<em>$2</em>')
    .replace(/\[([^\]]+)\]\((https?:[^)]+)\)/g, '<a href="$2" target="_blank" rel="noopener">$1</a>')
    .replace(/(^|\s)(https?:\/\/[^\s<]+)/g, '$1<a href="$2" target="_blank" rel="noopener">$2</a>');

  const lines = src.split('\n');
  const out = [];
  let i = 0, list = null;

  const closeList = () => { if (list) { out.push(`</${list}>`); list = null; } };

  while (i < lines.length) {
    const ln = lines[i];

    if (/^\s*$/.test(ln)) { closeList(); i++; continue; }

    if (/^---+\s*$/.test(ln)) { closeList(); out.push('<hr>'); i++; continue; }

    const hd = ln.match(/^(#{1,4})\s+(.*)$/);
    if (hd) {
      closeList();
      const lvl = Math.min(hd[1].length + 1, 4);   // # -> h2, so page h1 stays unique
      out.push(`<h${lvl}>${inline(hd[2])}</h${lvl}>`);
      i++; continue;
    }

    if (/^\s*```/.test(ln)) {
      closeList();
      const buf = [];
      i++;
      while (i < lines.length && !/^\s*```/.test(lines[i])) buf.push(lines[i++]);
      i++;
      out.push(`<pre><code>${esc(buf.join('\n'))}</code></pre>`);
      continue;
    }

    if (/^\s*\|/.test(ln)) {
      closeList();
      const rows = [];
      while (i < lines.length && /^\s*\|/.test(lines[i])) rows.push(lines[i++]);
      const cells = r => r.trim().replace(/^\||\|$/g, '').split('|').map(c => c.trim());
      const body = rows.filter(r => !/^\s*\|[\s\-:|]+\|\s*$/.test(r));
      if (body.length) {
        const head = cells(body[0]);
        out.push('<div class="table-wrap"><table><thead><tr>' +
          head.map(c => `<th>${inline(c)}</th>`).join('') + '</tr></thead><tbody>' +
          body.slice(1).map(r => '<tr>' + cells(r).map(c => `<td>${inline(c)}</td>`).join('') + '</tr>').join('') +
          '</tbody></table></div>');
      }
      continue;
    }

    if (/^\s*>/.test(ln)) {
      closeList();
      const buf = [];
      while (i < lines.length && /^\s*>/.test(lines[i])) buf.push(lines[i++].replace(/^\s*>\s?/, ''));
      out.push(`<blockquote class="md-quote">${inline(buf.join(' '))}</blockquote>`);
      continue;
    }

    const li = ln.match(/^\s*[-*]\s+(.*)$/);
    if (li) {
      if (list !== 'ul') { closeList(); out.push('<ul>'); list = 'ul'; }
      out.push(`<li>${inline(li[1])}</li>`);
      i++; continue;
    }
    const oli = ln.match(/^\s*\d+\.\s+(.*)$/);
    if (oli) {
      if (list !== 'ol') { closeList(); out.push('<ol>'); list = 'ol'; }
      out.push(`<li>${inline(oli[1])}</li>`);
      i++; continue;
    }

    closeList();
    const buf = [ln];
    i++;
    while (i < lines.length && !/^\s*$/.test(lines[i]) &&
           !/^(#{1,4}\s|\s*[-*]\s|\s*\d+\.\s|\s*\||\s*>|---+\s*$|\s*```)/.test(lines[i])) {
      buf.push(lines[i++]);
    }
    out.push(`<p>${inline(buf.join(' '))}</p>`);
  }
  closeList();
  return out.join('\n');
}

/* Render one context/*.md file into a card. */
function doc(name, opts = {}) {
  const src = OS?.docs?.[name];
  if (!src) return h('p', { class: 'tiny' }, `context/${name}.md not in the build.`);
  const body = h('div', { class: 'md', html: md(opts.from ? sliceDoc(src, opts.from, opts.to) : src) });
  return opts.bare ? body : h('div', { class: 'card md-card' }, body);
}

/* Pull one "## Heading" section out of a doc, the way tools/section.sh does. */
function sliceDoc(src, from, to) {
  const lines = src.split('\n');
  let a = lines.findIndex(l => l.trim().toLowerCase().startsWith('## ' + from.toLowerCase()));
  if (a < 0) return src;
  let b = lines.length;
  for (let i = a + 1; i < lines.length; i++) {
    if (/^##\s/.test(lines[i])) { b = i; break; }
  }
  return lines.slice(a, b).join('\n');
}

/* ------------------------------------------------------------ DOM helpers */

function h(tag, attrs = {}, ...kids) {
  const n = document.createElement(tag);
  for (const k in attrs) {
    if (k === 'class') n.className = attrs[k];
    else if (k === 'html') n.innerHTML = attrs[k];
    else if (k.startsWith('on')) n.addEventListener(k.slice(2).toLowerCase(), attrs[k]);
    else if (attrs[k] !== null && attrs[k] !== undefined) n.setAttribute(k, attrs[k]);
  }
  kids.flat().forEach(c => {
    if (c === null || c === undefined || c === false) return;
    n.appendChild(typeof c === 'string' || typeof c === 'number'
      ? document.createTextNode(String(c)) : c);
  });
  return n;
}

const $ = sel => document.querySelector(sel);
const mount = (sel, ...nodes) => {
  const t = $(sel);
  if (t) nodes.flat().forEach(n => n && t.appendChild(n));
  return t;
};

