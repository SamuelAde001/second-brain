function chrome(active) {
  const root = document.body.dataset.root || '';
  const bar = h('div', { class: 'topbar' },
    h('div', { class: 'topbar-in' },
      h('a', { class: 'brand', href: root + 'index.html' },
        h('span', { class: 'brand-mark' }, 'S'),
        h('span', {}, 'Samuelsignals ', h('small', {}, 'OS'))),
      h('nav', { class: 'nav' },
        PAGES.map(([id, label, dir]) =>
          h('a', {
            class: id === active ? 'on' : '',
            href: root + dir + id + '.html',
          }, label)))));
  document.body.prepend(bar);

  const gen = OS?.generated ? new Date(OS.generated) : null;
  mount('body', h('footer', {},
    h('div', { class: 'wrap' },
      h('p', {},
        'Generated from ', h('code', {}, 'context/'), ' by ',
        h('code', {}, 'tools/site/build.py'),
        gen ? ` — ${gen.toLocaleString('en-GB')}` : ''),
      h('p', { class: 'tiny', style: 'margin-top:6px' },
        'This site is a view of the record, never the record itself. ' +
        'If a number here is wrong, the fix is in context/ and the site is rebuilt.'))));
}

function guard() {
  if (OS) return true;
  document.body.prepend(h('div', { class: 'wrap' },
    h('div', { class: 'callout bad', style: 'margin-top:24px' },
      h('span', { class: 'ico' }, '⚠'),
      h('div', {},
        h('p', {}, h('strong', {}, 'No data loaded.')),
        h('p', {}, 'Run ', h('code', {}, 'python tools/site/build.py'),
          ' to generate ', h('code', {}, 'site/data/os.js'), '.')))));
  return false;
}

/* --------------------------------------------------------- shared builders */

const verdictPill = v =>
  h('span', { class: 'pill ' + (v || 'open').toLowerCase() }, v || 'OPEN');

function stat(k, v, note, cls = '') {
  return h('div', { class: 'stat' },
    h('div', { class: 'k' }, k),
    h('div', { class: `v mono ${cls}` }, v),
    note ? h('div', { class: 'n' }, note) : null);
}

function statCard(k, v, note, cls = '') {
  return h('div', { class: 'card' }, stat(k, v, note, cls));
}

function callout(kind, icon, ...paras) {
  return h('div', { class: 'callout ' + kind },
    h('span', { class: 'ico' }, icon),
    h('div', {}, paras.map(p => typeof p === 'string' ? h('p', { html: p }) : p)));
}

function toggle(title, sub, ...body) {
  return h('details', { class: 'tg' },
    h('summary', {}, title, sub ? h('span', { class: 'sub' }, sub) : null),
    h('div', { class: 'tg-body' }, body));
}

function bar(value, max, cls = '') {
  const p = max ? Math.max(0, Math.min(100, (value / max) * 100)) : 0;
  return h('div', { class: 'bar' }, h('i', { class: cls, style: `width:${p}%` }));
}

function table(cols, rows) {
  return h('div', { class: 'table-wrap' },
    h('table', {},
      h('thead', {}, h('tr', {}, cols.map(c =>
        h('th', { class: c.num ? 'num' : '' }, c.label || c)))),
      h('tbody', {}, rows.map(r => h('tr', {}, r.map((cell, i) =>
        h('td', { class: (cols[i] && cols[i].num ? 'num ' : '') + (cols[i] && cols[i].cls || '') },
          cell)))))));
}

/* Score colour: the bands are deliberately harsh. 70 is not a good day here —
   25 Aug shipped and scored 70 because it cost a 19-hour night. */
const scoreClass = s =>
  s === null || s === undefined ? '' : s >= 85 ? 'green' : s >= 60 ? 'amber' : 'red';

function pageHead(eyebrow, title, lede) {
  return h('div', { class: 'page-head' },
    h('div', { class: 'eyebrow' }, eyebrow),
    h('h1', {}, title),
    lede ? h('p', { class: 'lede', html: lede }) : null);
}

function section(title) {
  return h('h2', {}, title);
}

function chartCard(title, sub, id, note) {
  return h('div', { class: 'card' },
    h('div', { class: 'card-h' }, h('h3', {}, title), sub ? h('span', { class: 'sub' }, sub) : null),
    h('div', { id }),
    note ? h('p', { class: 'chart-note', html: note }) : null);
}

/* Chart notes carry inline <strong>. Passing an HTML string as a child would
   text-node it, so notes go through here. */
function note(html) {
  return h('p', { class: 'chart-note', html });
}

function legend(items) {
  return h('div', { class: 'chart-legend' },
    items.map(([colour, label]) =>
      h('span', {}, h('i', { style: `background:${colour}` }), label)));
}

/* Every static callout and chart note on this site lives in context/site.json
   under `notes`, keyed by page and id. Rewriting a sentence — a figure that
   moved, a rule that died — is a data edit, never a code edit. That is Samuel's
   rule from 2026-09-02, and this function is the whole of the reading half.

   A missing id renders a visible marker rather than nothing. Silence is how the
   dead "While fasting" card survived a rule change: the page looked fine. */
function notesFor(page, id) {
  const entry = ((OS.notes || {})[page] || {})[id];
  if (!entry) {
    return h('p', { class: 'chart-note' },
      `[missing note ${page}/${id} — add it to notes.${page}.${id} in context/site.json]`);
  }
  if (entry.type === 'note') return note(entry.html);
  return callout(entry.kind, entry.icon, ...(entry.paras || []));
}

